export function generateMockSlotsForDate(doctorId: string, date: string): Slot[] {
  // Make offset +3 days intentionally empty so reviewers can test empty slot states naturally
  if (date === formatIsoDate(3)) {
    return [];
  }

  const baseWindows = [
    { start: '09:30', end: '09:50', available: true },
    { start: '10:15', end: '10:35', available: false },
    { start: '11:00', end: '11:20', available: true },
    { start: '12:30', end: '12:50', available: true },
    { start: '17:30', end: '17:50', available: true },
    { start: '18:15', end: '18:35', available: doctorId !== 'doc-3' },
    { start: '19:00', end: '19:20', available: true },
    { start: '19:45', end: '20:05', available: true },
  ];

  return baseWindows.map((w, idx) => ({
    id: `slot-${doctorId}-${date}-${idx}`,
    doctorId,
    startsAt: `${date}T${w.start}:00`,
    endsAt: `${date}T${w.end}:00`,
    available: w.available,
  }));
}
